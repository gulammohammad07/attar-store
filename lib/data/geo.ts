export function normalizePlace(value: string): string {
  return value.toLowerCase().replace(/\s+/g, " ").trim();
}

/** Ranked keyword matches: prefix hits first, then alphabetical. */
export function matchOptions(
  query: string,
  options: readonly string[],
  limit = 8,
): string[] {
  const q = normalizePlace(query);
  if (!q) return [];
  const matches = options.filter((option) =>
    normalizePlace(option).includes(q),
  );
  matches.sort((a, b) => {
    const aPrefix = normalizePlace(a).startsWith(q) ? 0 : 1;
    const bPrefix = normalizePlace(b).startsWith(q) ? 0 : 1;
    if (aPrefix !== bPrefix) return aPrefix - bPrefix;
    return normalizePlace(a).localeCompare(normalizePlace(b));
  });
  return matches.slice(0, limit);
}

/** State suggestions for a typed country — empty when unknown. */
export function statesForCountry(country: string): readonly string[] {
  if (!country) return [];
  const normalized = normalizePlace(country);
  const key = Object.keys(STATES_BY_COUNTRY).find(
    (name) => normalizePlace(name) === normalized,
  );
  return key ? STATES_BY_COUNTRY[key] : [];
}

/** City suggestions — shipped for India; other countries fall back to manual entry. */
export function citiesForCountry(country: string): readonly string[] {
  return normalizePlace(country) === "india" ? INDIA_CITIES : [];
}
